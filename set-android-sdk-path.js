/**
 * Android SDK 경로를 자동으로 찾아서 local.properties 파일을 생성하는 스크립트
 */
const fs = require('fs');
const path = require('path');
const os = require('os');

const androidDir = path.join(__dirname, 'android');
const localPropertiesPath = path.join(androidDir, 'local.properties');

// Android 디렉토리가 없으면 생성
if (!fs.existsSync(androidDir)) {
  console.log('⚠ Android 디렉토리가 없습니다. 먼저 "npx cap add android"를 실행하세요.');
  process.exit(1);
}

// 가능한 SDK 경로 목록
function getPossibleSdkPaths() {
  const homeDir = os.homedir();
  const paths = [];

  if (process.platform === 'win32') {
    // Windows
    const localAppData = process.env.LOCALAPPDATA || path.join(homeDir, 'AppData', 'Local');
    paths.push(
      path.join(localAppData, 'Android', 'Sdk'),
      path.join(homeDir, 'AppData', 'Local', 'Android', 'Sdk'),
      'C:\\Android\\Sdk',
      process.env.ANDROID_HOME
    );
  } else if (process.platform === 'darwin') {
    // macOS
    paths.push(
      path.join(homeDir, 'Library', 'Android', 'sdk'),
      path.join(homeDir, 'Library', 'Android', 'Sdk'),
      '/Users/Shared/Android/sdk',
      process.env.ANDROID_HOME
    );
  } else {
    // Linux
    paths.push(
      path.join(homeDir, 'Android', 'Sdk'),
      path.join(homeDir, '.android', 'sdk'),
      '/opt/android-sdk',
      '/usr/lib/android-sdk',
      process.env.ANDROID_HOME
    );
  }

  return paths.filter(p => p && fs.existsSync(p));
}

// SDK 경로 검증
function validateSdkPath(sdkPath) {
  if (!sdkPath || !fs.existsSync(sdkPath)) {
    return false;
  }

  // platform-tools 디렉토리가 있는지 확인
  const platformTools = path.join(sdkPath, 'platform-tools');
  const platforms = path.join(sdkPath, 'platforms');
  
  return fs.existsSync(platformTools) || fs.existsSync(platforms);
}

// SDK 경로 찾기
function findSdkPath() {
  // 1. 환경 변수 확인
  if (process.env.ANDROID_HOME && validateSdkPath(process.env.ANDROID_HOME)) {
    return process.env.ANDROID_HOME;
  }

  // 2. 가능한 경로 목록에서 찾기
  const possiblePaths = getPossibleSdkPaths();
  for (const sdkPath of possiblePaths) {
    if (validateSdkPath(sdkPath)) {
      return sdkPath;
    }
  }

  return null;
}

// local.properties 파일 생성
function createLocalProperties(sdkPath) {
  // Windows 경로는 백슬래시를 이스케이프해야 함
  let escapedPath = sdkPath.replace(/\\/g, '\\\\');
  
  const content = `## This file is automatically generated by Android tool.
# Do not modify this file -- YOUR CHANGES WILL BE ERASED!
#
# This file should *NOT* be checked into Version Control Systems,
# as it contains information specific to your local configuration.
#
# Location of the SDK. This is only used by Gradle.
# For customization when using a Version Control System, please read the
# header note.
sdk.dir=${escapedPath}
`;

  fs.writeFileSync(localPropertiesPath, content, 'utf8');
  console.log(`✓ local.properties 파일이 생성되었습니다: ${localPropertiesPath}`);
  console.log(`  SDK 경로: ${sdkPath}`);
}

// 메인 실행
console.log('Android SDK 경로를 찾는 중...\n');

const sdkPath = findSdkPath();

if (sdkPath) {
  createLocalProperties(sdkPath);
  console.log('\n✅ 완료! 이제 Android 프로젝트를 빌드할 수 있습니다.');
} else {
  console.log('❌ Android SDK를 찾을 수 없습니다.\n');
  console.log('다음 중 하나를 시도하세요:');
  console.log('1. Android Studio를 설치하고 SDK를 설정하세요');
  console.log('2. ANDROID_HOME 환경 변수를 설정하세요');
  console.log('3. 수동으로 android/local.properties 파일을 생성하세요:\n');
  console.log('   sdk.dir=YOUR_SDK_PATH\n');
  
  if (process.platform === 'win32') {
    console.log('일반적인 Windows 경로:');
    console.log('  C:\\Users\\YourUsername\\AppData\\Local\\Android\\Sdk');
  } else if (process.platform === 'darwin') {
    console.log('일반적인 macOS 경로:');
    console.log('  ~/Library/Android/sdk');
  } else {
    console.log('일반적인 Linux 경로:');
    console.log('  ~/Android/Sdk');
  }
  
  process.exit(1);
}

